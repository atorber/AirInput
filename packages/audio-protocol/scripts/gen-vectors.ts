import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CodecId,
  PacketType,
  encodeFrame,
  encodeStartPayload,
} from "../src/index.js";

function toHex(bytes: Uint8Array): string {
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

const startPayload = encodeStartPayload({
  sampleRate: 48_000,
  channels: 1,
  frameMs: 20,
  bitrate: 32_000,
  codec: CodecId.Opus,
});

const cases = [
  {
    name: "empty_ping",
    packetType: PacketType.Ping,
    sequence: 0,
    timestamp: "0",
    payload: new Uint8Array(0),
  },
  {
    name: "start_48k_mono_opus",
    packetType: PacketType.Start,
    sequence: 1,
    timestamp: "1710000000000",
    payload: startPayload,
  },
  {
    name: "audio_tiny",
    packetType: PacketType.Audio,
    sequence: 42,
    timestamp: "1710000000020",
    payload: Uint8Array.from([0xde, 0xad, 0xbe, 0xef]),
  },
];

const out = {
  description:
    "Cross-language header vectors. Multi-byte fields are big-endian. Generated by scripts/gen-vectors.ts",
  cases: cases.map((c) => {
    const frame = encodeFrame(
      c.packetType,
      c.sequence,
      BigInt(c.timestamp),
      c.payload,
    );
    return {
      name: c.name,
      packetType: c.packetType,
      sequence: c.sequence,
      timestamp: c.timestamp,
      payloadHex: toHex(c.payload),
      frameHex: toHex(frame),
    };
  }),
};

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "../testdata/header-vectors.json");
writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${target}`);
